#!/usr/bin/env node
// Emit the rendered wall boxes as a C header so the route can test the body
// against the same geometry the paper model draws. The boxes come from
// public/rpd/plan.json after tools/rpd_wall_openings.mjs opens the doorways the
// nav graph needs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const plan = JSON.parse(readFileSync(resolve(root, "public/rpd/plan.json"), "utf8"));
const out = resolve(root, "native/gen/rpd_walls_gen.h");
const CELL = 2.0;
const MARGIN = 4.0;

const walls = [];
for (const floor of plan.floors) {
  for (const box of floor.boxes) {
    if (box.faces === "top") continue;
    walls.push({
      x0: box.x0, z0: box.z0, x1: box.x1, z1: box.z1,
      y0: box.y0, y1: box.y1, floor: floor.index,
    });
  }
}

let minX = Infinity, maxX = -Infinity, minZ = Infinity, maxZ = -Infinity;
for (const wall of walls) {
  minX = Math.min(minX, wall.x0); maxX = Math.max(maxX, wall.x1);
  minZ = Math.min(minZ, wall.z0); maxZ = Math.max(maxZ, wall.z1);
}
minX -= MARGIN; maxX += MARGIN; minZ -= MARGIN; maxZ += MARGIN;
const cols = Math.floor((maxX - minX) / CELL) + 1;
const rows = Math.floor((maxZ - minZ) / CELL) + 1;

const cells = new Map();
for (let i = 0; i < walls.length; i += 1) {
  const wall = walls[i];
  const gx0 = Math.floor((wall.x0 - minX) / CELL);
  const gx1 = Math.floor((wall.x1 - minX) / CELL);
  const gz0 = Math.floor((wall.z0 - minZ) / CELL);
  const gz1 = Math.floor((wall.z1 - minZ) / CELL);
  for (let gx = gx0; gx <= gx1; gx += 1) {
    for (let gz = gz0; gz <= gz1; gz += 1) {
      const key = gx * rows + gz;
      if (!cells.has(key)) cells.set(key, []);
      cells.get(key).push(i);
    }
  }
}
const start = new Uint32Array(cols * rows + 1);
const items = [];
for (let key = 0; key < cols * rows; key += 1) {
  start[key] = items.length;
  const list = cells.get(key);
  if (list) items.push(...list);
}
start[cols * rows] = items.length;

const f = (value) => Number(value).toFixed(4);
const lines = [
  "#pragma once",
  "",
  "/* Generated by tools/rpd_walls.mjs from public/rpd/plan.json. */",
  "",
  `#define RPD_WALL_COUNT ${walls.length}`,
  `#define RPD_WALL_GRID_COLS ${cols}`,
  `#define RPD_WALL_GRID_ROWS ${rows}`,
  `#define RPD_WALL_GRID_CELL ${f(CELL)}f`,
  `#define RPD_WALL_GRID_MIN_X ${f(minX)}f`,
  `#define RPD_WALL_GRID_MIN_Z ${f(minZ)}f`,
  "",
  "typedef struct {",
  "    float x0, z0, x1, z1;",
  "    float y0, y1;",
  "    unsigned char floor;",
  "} rpd_wall_t;",
  "",
  "static const rpd_wall_t rpd_walls[RPD_WALL_COUNT] = {",
];
for (const wall of walls) {
  lines.push(
    `    { ${f(wall.x0)}f, ${f(wall.z0)}f, ${f(wall.x1)}f, ${f(wall.z1)}f, ` +
      `${f(wall.y0)}f, ${f(wall.y1)}f, ${wall.floor} },`,
  );
}
lines.push("};", "", "static const unsigned int rpd_wall_grid_start[] = {");
for (let i = 0; i < start.length; i += 16) {
  lines.push(`    ${Array.from(start.subarray(i, i + 16)).join(", ")},`);
}
lines.push("};", "", "static const unsigned short rpd_wall_grid_items[] = {");
for (let i = 0; i < items.length; i += 16) {
  lines.push(`    ${items.slice(i, i + 16).join(", ")},`);
}
if (items.length === 0) lines.push("    0,");
lines.push("};", "");

writeFileSync(out, lines.join("\n"));
console.log(`wrote native/gen/rpd_walls_gen.h: ${walls.length} walls, ${cols}x${rows} grid, ${items.length} entries`);
