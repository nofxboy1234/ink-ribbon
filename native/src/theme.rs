pub type Rgba = [u8; 4];

pub const BACKGROUND: Rgba = [0xF6, 0xF1, 0xE6, 0xFF];

pub const PAPER: Rgba = [0xFD, 0xFB, 0xF6, 0xFF];
pub const CREAM: Rgba = [0xFA, 0xF3, 0xE7, 0xFF];
pub const BEIGE: Rgba = [0xE1, 0xEB, 0xED, 0xFF];
pub const SKY: Rgba = [0x4C, 0x98, 0xBF, 0xFF];
pub const STEEL: Rgba = [0x57, 0xA5, 0xD7, 0xFF];
pub const NAVY: Rgba = [0x0A, 0x2B, 0x65, 0xFF];
pub const SLATE: Rgba = [0x6D, 0x8F, 0xA7, 0xFF];
pub const SALMON: Rgba = [0xD9, 0xBE, 0xB3, 0xFF];

pub const PURPLE: Rgba = [0xBB, 0xB3, 0xC8, 0xFF];
pub const PINK: Rgba = [0xDD, 0x8F, 0x98, 0xFF];
pub const GREEN: Rgba = [0x6F, 0xB7, 0xA8, 0xFF];
pub const TEAL: Rgba = [0x7F, 0xC4, 0xC4, 0xFF];
pub const AMBER: Rgba = [0xD9, 0xA8, 0x6C, 0xFF];
pub const LIME: Rgba = [0xC8, 0xC7, 0x7A, 0xFF];
pub const RED: Rgba = [0xB8, 0x5C, 0x57, 0xFF];

pub const GRID_LINE: Rgba = [0x6D, 0x8F, 0xA7, 0x40];
pub const WALL: Rgba = [0x0A, 0x2B, 0x65, 0xFF];

pub fn with_alpha(color: Rgba, alpha: u8) -> Rgba {
    [color[0], color[1], color[2], alpha]
}

pub fn to_f32(color: Rgba) -> [f32; 4] {
    [
        color[0] as f32 / 255.0,
        color[1] as f32 / 255.0,
        color[2] as f32 / 255.0,
        color[3] as f32 / 255.0,
    ]
}
