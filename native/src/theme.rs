pub type Rgba = [u8; 4];

pub const BACKGROUND: Rgba = [0x20, 0x1E, 0x1C, 0xFF];

pub const PAPER: Rgba = [0xFC, 0xF8, 0xED, 0xFF];
pub const CREAM: Rgba = [0xFC, 0xF8, 0xED, 0xFF];
pub const BEIGE: Rgba = [0xE0, 0xDA, 0xC2, 0xFF];
pub const SKY: Rgba = [0x6D, 0xB0, 0xDB, 0xFF];
pub const STEEL: Rgba = [0x08, 0x45, 0x86, 0xFF];
pub const NAVY: Rgba = [0x04, 0x25, 0x68, 0xFF];
pub const SLATE: Rgba = [0x6D, 0x7D, 0x8A, 0xFF];
pub const SALMON: Rgba = [0xE7, 0x90, 0x7F, 0xFF];

pub const PURPLE: Rgba = [0x94, 0x6D, 0xDB, 0xFF];
pub const PINK: Rgba = [0xDB, 0x6D, 0x94, 0xFF];
pub const GREEN: Rgba = [0x6D, 0xDB, 0xA8, 0xFF];
pub const TEAL: Rgba = [0x6D, 0xDB, 0xD4, 0xFF];
pub const AMBER: Rgba = [0xDB, 0xAA, 0x6D, 0xFF];
pub const LIME: Rgba = [0xD9, 0xDB, 0x6D, 0xFF];
pub const RED: Rgba = [0xFF, 0x40, 0x5D, 0xFF];

pub const GRID_LINE: Rgba = [0x6D, 0x7D, 0x8A, 0x40];
pub const WALL: Rgba = [0xFC, 0xF8, 0xED, 0xE6];

pub fn with_alpha(color: Rgba, alpha: u8) -> Rgba {
    [color[0], color[1], color[2], alpha]
}

pub fn to_f32(color: Rgba) -> [f32; 4] {
    [
        color[0] as f32 / 255.0,
        color[1] as f32 / 255.0,
        color[2] as f32 / 255.0,
        color[3] as f32 / 255.0,
    ]
}
