    "in vec2 position;\n"
    "out vec2 v_uv;\n"
    "void main() {\n"
    "  v_uv = position * 0.5 + 0.5;\n"
    "  gl_Position = vec4(position, 0.0, 1.0);\n"
    "}\n";

const char *composite_fs_source =
    "#version 300 es\n"
    "precision highp float;\n"
    "uniform sampler2D u_tex;\n"
    "uniform sampler2D u_normal;\n"
    "in vec2 v_uv;\n"
    "out vec4 frag_color;\n"
    "void main() {\n"
    "  vec2 texel = 1.0 / vec2(textureSize(u_tex, 0));\n"
    "  vec3 c = texture(u_tex, v_uv).rgb;\n"
    "  vec4 nC = texture(u_normal, v_uv);\n"
    "  bool marker = abs(nC.a - 0.5) < 0.2;\n"
    "  vec4 n00 = texture(u_normal, v_uv + texel * vec2(-1.0, -1.0));\n"
    "  vec4 n10 = texture(u_normal, v_uv + texel * vec2( 0.0, -1.0));\n"
    "  vec4 n20 = texture(u_normal, v_uv + texel * vec2( 1.0, -1.0));\n"
    "  vec4 n01 = texture(u_normal, v_uv + texel * vec2(-1.0,  0.0));\n"
    "  vec4 n21 = texture(u_normal, v_uv + texel * vec2( 1.0,  0.0));\n"
    "  vec4 n02 = texture(u_normal, v_uv + texel * vec2(-1.0,  1.0));\n"
    "  vec4 n12 = texture(u_normal, v_uv + texel * vec2( 0.0,  1.0));\n"
    "  vec4 n22 = texture(u_normal, v_uv + texel * vec2( 1.0,  1.0));\n"
    "  vec3 c00 = texture(u_tex, v_uv + texel * vec2(-1.0, -1.0)).rgb;\n"
    "  vec3 c10 = texture(u_tex, v_uv + texel * vec2( 0.0, -1.0)).rgb;\n"
    "  vec3 c20 = texture(u_tex, v_uv + texel * vec2( 1.0, -1.0)).rgb;\n"
    "  vec3 c01 = texture(u_tex, v_uv + texel * vec2(-1.0,  0.0)).rgb;\n"
    "  vec3 c21 = texture(u_tex, v_uv + texel * vec2( 1.0,  0.0)).rgb;\n"
    "  vec3 c02 = texture(u_tex, v_uv + texel * vec2(-1.0,  1.0)).rgb;\n"
    "  vec3 c12 = texture(u_tex, v_uv + texel * vec2( 0.0,  1.0)).rgb;\n"
    "  vec3 c22 = texture(u_tex, v_uv + texel * vec2( 1.0,  1.0)).rgb;\n"
    "  if (abs(n00.a - 0.5) < 0.2) { n00 = nC; c00 = c; }\n"
    "  if (abs(n10.a - 0.5) < 0.2) { n10 = nC; c10 = c; }\n"
    "  if (abs(n20.a - 0.5) < 0.2) { n20 = nC; c20 = c; }\n"
    "  if (abs(n01.a - 0.5) < 0.2) { n01 = nC; c01 = c; }\n"
    "  if (abs(n21.a - 0.5) < 0.2) { n21 = nC; c21 = c; }\n"
    "  if (abs(n02.a - 0.5) < 0.2) { n02 = nC; c02 = c; }\n"
    "  if (abs(n12.a - 0.5) < 0.2) { n12 = nC; c12 = c; }\n"
    "  if (abs(n22.a - 0.5) < 0.2) { n22 = nC; c22 = c; }\n"
    "  vec3 gx = -c00 - 2.0 * c01 - c02 + c20 + 2.0 * c21 + c22;\n"
    "  vec3 gy = -c00 - 2.0 * c10 - c20 + c02 + 2.0 * c12 + c22;\n"
    "  float colorEdge = smoothstep(0.12, 0.42, length(gx) + length(gy));\n"
    "  vec3 nc = normalize(nC.xyz * 2.0 - 1.0);\n"
    "  vec3 nn00 = normalize(n00.xyz * 2.0 - 1.0);\n"
    "  vec3 nn10 = normalize(n10.xyz * 2.0 - 1.0);\n"
    "  vec3 nn20 = normalize(n20.xyz * 2.0 - 1.0);\n"
    "  vec3 nn01 = normalize(n01.xyz * 2.0 - 1.0);\n"
    "  vec3 nn21 = normalize(n21.xyz * 2.0 - 1.0);\n"
    "  vec3 nn02 = normalize(n02.xyz * 2.0 - 1.0);\n"
    "  vec3 nn12 = normalize(n12.xyz * 2.0 - 1.0);\n"
    "  vec3 nn22 = normalize(n22.xyz * 2.0 - 1.0);\n"
    "  float nd = max(1.0 - dot(nc, nn00), max(1.0 - dot(nc, nn10), max(1.0 - dot(nc, nn20), max(1.0 - dot(nc, nn01), max(1.0 - dot(nc, nn21), max(1.0 - dot(nc, nn02), max(1.0 - dot(nc, nn12), 1.0 - dot(nc, nn22))))))));\n"
    "  float normalEdge = smoothstep(0.18, 0.5, nd);\n"
    "  float edge = marker ? 0.0 : max(colorEdge, normalEdge);\n"
    "  vec2 q = v_uv - 0.5;\n"
    "  float vig = smoothstep(1.05, 0.15, length(q));\n"
    "  float grain = fract(sin(dot(gl_FragCoord.xy, vec2(12.9898, 78.233))) * 43758.5453) - 0.5;\n"
    "  vec3 col = c * (0.982 + 0.018 * vig) + grain * 0.0035;\n"
    "  col = mix(col, vec3(0.085, 0.082, 0.078), edge * 0.92);\n"
    "  frag_color = vec4(col, 1.0);\n"
    "}\n";
