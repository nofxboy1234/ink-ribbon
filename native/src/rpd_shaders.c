const char *composite_fs_source =
    "#version 300 es\n"
    "precision highp float;\n"
    "uniform sampler2D u_tex;\n"
    "in vec2 v_uv;\n"
    "out vec4 frag_color;\n"
    "void main() {\n"
    "  vec2 texel = 1.0 / vec2(textureSize(u_tex, 0));\n"
    "  vec3 c = texture(u_tex, v_uv).rgb;\n"
    "  vec3 l00 = texture(u_tex, v_uv + texel * vec2(-1.0, -1.0)).rgb;\n"
    "  vec3 l10 = texture(u_tex, v_uv + texel * vec2( 0.0, -1.0)).rgb;\n"
    "  vec3 l20 = texture(u_tex, v_uv + texel * vec2( 1.0, -1.0)).rgb;\n"
    "  vec3 l01 = texture(u_tex, v_uv + texel * vec2(-1.0,  0.0)).rgb;\n"
    "  vec3 l21 = texture(u_tex, v_uv + texel * vec2( 1.0,  0.0)).rgb;\n"
    "  vec3 l02 = texture(u_tex, v_uv + texel * vec2(-1.0,  1.0)).rgb;\n"
    "  vec3 l12 = texture(u_tex, v_uv + texel * vec2( 0.0,  1.0)).rgb;\n"
    "  vec3 l22 = texture(u_tex, v_uv + texel * vec2( 1.0,  1.0)).rgb;\n"
    "  vec3 gx = -l00 - 2.0 * l01 - l02 + l20 + 2.0 * l21 + l22;\n"
    "  vec3 gy = -l00 - 2.0 * l10 - l20 + l02 + 2.0 * l12 + l22;\n"
    "  float edge = smoothstep(0.12, 0.42, length(gx) + length(gy));\n"
    "  vec2 q = v_uv - 0.5;\n"
    "  float vig = smoothstep(1.05, 0.15, length(q));\n"
    "  float grain = fract(sin(dot(gl_FragCoord.xy, vec2(12.9898, 78.233))) * 43758.5453) - 0.5;\n"
    "  vec3 col = c * (0.982 + 0.018 * vig) + grain * 0.0035;\n"
    "  col = mix(col, vec3(0.085, 0.082, 0.078), edge * 0.92);\n"
    "  frag_color = vec4(col, 1.0);\n"
    "}\n";
