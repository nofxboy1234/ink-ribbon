export function distance3(a: Vec3, b: Vec3): number {
  return Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);
}

export function itemPoint(item: Item): Vec3 {
  return [item.x, item.y, item.z];
}
